class Canvas:
    """一块 8 位 RGB 画布。所有坐标都是**像素**，左上角为 (0,0)。"""

    def __init__(self, width: int, height: int, bg: tuple[int, int, int] = (255, 255, 255)):
        """建画布并铺底色。buf 是扁平的字节数组：每像素 3 字节（R、G、B）。"""
        self.w = int(width)
        self.h = int(height)
        self.buf = bytearray(bytes(bg) * (self.w * self.h))

    def _px(self, x: int, y: int, color: tuple[int, int, int]) -> None:
        """画一个像素。越界**直接丢弃**（不报错）—— 线宽/斜接常会甩出边界一点点。"""
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.buf[i] = color[0]
            self.buf[i + 1] = color[1]
            self.buf[i + 2] = color[2]

    def line(self, x0, y0, x1, y1, color, thick: int = 1, dash=None) -> None:
        """Bresenham 直线。

        Args:
            thick: 线宽（正方形笔刷，粗线向右下扩）。
            dash: None = 实线；`(实长, 虚长)` 像素 = 虚线。虚线靠步数取模实现。
        """
        x0, y0 = int(round(x0)), int(round(y0))
        x1, y1 = int(round(x1)), int(round(y1))
        dx = abs(x1 - x0)
        dy = -abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx + dy
        on, off = dash if dash else (0, 0)
        period = on + off
        step = 0
        while True:
            if not period or (step % period) < on:
                for ox in range(thick):
                    for oy in range(thick):
                        self._px(x0 + ox, y0 + oy, color)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy
            step += 1

    def poly(self, pts, color, thick: int = 1, dash=None) -> None:
        """画闭合折线：逐条边调 line，最后一条边把末点接回首点。"""
        n = len(pts)
        for i in range(n):
            a, b = pts[i], pts[(i + 1) % n]
            self.line(a[0], a[1], b[0], b[1], color, thick, dash)

    def circle(self, cx, cy, r, color, thick: int = 1) -> None:
        """中点画圆（只画圆环，不填充）—— 用来画禁止放置区。"""
        cx, cy, r = int(round(cx)), int(round(cy)), int(round(r))
        x, y, d = r, 0, 1 - r
        while x >= y:
            for px, py in ((x, y), (y, x), (-x, y), (-y, x),
                           (-x, -y), (-y, -x), (x, -y), (y, -x)):
                for ox in range(thick):
                    for oy in range(thick):
                        self._px(cx + px + ox, cy + py + oy, color)
            y += 1
            if d < 0:
                d += 2 * y + 1
            else:
                x -= 1
                d += 2 * (y - x) + 1

    def text(self, x, y, s: str, color, scale: int = 2) -> None:
        """画 5×7 点阵字。scale=2 → 每个点画成 2×2 像素；字符宽 6 个点（含 1 点间距）。"""
        cx = int(x)
        for ch in str(s).upper():
            art = FONT.get(ch)
            if art is None:                 # 字模里没有的字符：留空，不报错
                cx += 6 * scale
                continue
            for ry, row in enumerate(art.split("/")):
                for rx, flag in enumerate(row):
                    if flag == "#":
                        px = cx + rx * scale
                        py = int(y) + ry * scale
                        for dx in range(scale):
                            for dy in range(scale):
                                self._px(px + dx, py + dy, color)
            cx += 6 * scale

    def text_width(self, s: str, scale: int = 2) -> int:
        """一段文字的像素宽度（用来算右对齐/居中）。每字符 6 个点宽。"""
        return len(str(s)) * 6 * scale

    def write_png(self, path) -> None:
        """按 PNG 规范落盘：8 位 RGB、每行滤波 0。

        PNG 结构 = 签名 + IHDR（长宽/位深/颜色类型）+ IDAT（zlib 压缩的扫描行）+ IEND；
        每个数据块都要带 **CRC32**，写错了图片软件直接拒开。
        """
        raw = bytearray()
        stride = self.w * 3
        for y in range(self.h):
            raw.append(0)                                  # 滤波类型 0 = 不过滤
            raw += self.buf[y * stride:(y + 1) * stride]

        def chunk(tag: bytes, data: bytes) -> bytes:
            return (struct.pack(">I", len(data)) + tag + data
                    + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

        png = b"\x89PNG\r\n\x1a\n"                          # PNG 魔数（8 字节）
        png += chunk(b"IHDR", struct.pack(">IIBBBBB", self.w, self.h, 8, 2, 0, 0, 0))
        png += chunk(b"IDAT", zlib.compress(bytes(raw), 6))
        png += chunk(b"IEND", b"")
        with open(path, "wb") as f:
            f.write(png)
