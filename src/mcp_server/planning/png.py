# 零依赖 PNG 输出（纯标准库：zlib + struct）
#
# 【为什么手写、不引 Pillow】
#   规划层刻意保持"只吃标准库"：这样它在任何环境都能直接跑，
#   也不会给 MCP server 的依赖树添东西（加依赖是架构决定，归用户拍板）。
#
# 【支持范围（刻意做小）】
#   8 位 RGB、每行滤波 0（不压缩花活，只求确定）：
#   点 / 线（可虚线、可粗） / 闭合折线 / 圆环 / 5×7 点阵字。
#   只够画线框图，不做抗锯齿、不做透明、不做文字排版。
#
# 【字体是手写的 5×7 点阵】
#   ⚠ 字模写成 '#'/'.' 的 ASCII 形状，**肉眼可校对**：哪个字歪了一眼能看出。
#     发现某个字不对，改 FONT 里对应那一行即可（每行 7 组、每组 5 个字符，用 '/' 分隔）。
# =============================================================================

